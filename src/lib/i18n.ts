export type TranslationLang = "en" | "ar";

export function t<T extends keyof typeof translations.en>(
  section: T,
  key: keyof (typeof translations.en)[T],
  lang: TranslationLang
): string {
  const sec = translations[lang]?.[section] || translations.en[section];
  // @ts-expect-error key indexing is dynamic but type-safe via generics
  return sec[key] || translations.en[section][key] || "";
}

export function getLocalizedValue(
  field?: { en: string; ar?: string },
  lang: TranslationLang = "en"
): string {
  if (!field) return "";
  if (lang === "ar" && field.ar && field.ar.trim() !== "") {
    return field.ar.trim();
  }
  return field.en ? field.en.trim() : "";
}
